package top.rootu.dddplayer.model

/**
 * Калибровка анаглиф-очков из визарда для группы очков (фильтр "Калибровка").
 * A и B - светофильтры первого и второго цвета группы (например, красный и голубой), независимо от стороны.
 *
 * Утечка - сколько света дополнительного (чужого) цвета пропускает фильтр: через красный фильтр полный
 * голубой выглядит как красный с линейной яркостью leakA. Подбирается в визарде по исчезновению
 * двоения ("подавление двоения"), матрицы вычитают просочившееся изображение второго глаза.
 *
 * @param leakA утечка светофильтра A (линейная яркость 0..1)
 * @param leakB утечка светофильтра B (линейная яркость 0..1)
 */
data class AnaglyphCalibration(
    val leakA: Float = 0.033f,
    val leakB: Float = 0.033f
)
